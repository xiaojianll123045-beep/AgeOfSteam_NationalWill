        // ============ 开局分步教程 ============
        private static bool _introPending;
        private static int _introStep;
        private static float _timer;

        internal static void StartIntro()
        {
            try
            {
                if (TipState.Disabled("intro")) return;
                _introPending = true;
                _introStep = 0;
                _timer = 3f;   // 接管后 3 秒弹第一步
            }
            catch { }
        }

        internal static void ResetForNewCampaign()
        {
            _introPending = false;
            _introStep = 0;
            _timer = 0f;
        }

        internal static void Tick(float dt)
        {
            try
            {
                if (!_introPending) return;
                _timer -= dt;
                if (_timer > 0f) return;
                if (PanelInputGuard.AnyPopupActive()) { _timer = 1f; return; }
                ShowIntroStep();
            }
            catch { }
        }

        private static void ShowIntroStep()
        {
            try
            {
                string[] steps = IntroSteps();
                if (_introStep >= steps.Length)
                {
                    _introPending = false;
                    return;
                }
                string[] parts = steps[_introStep].Split('|');
                string title = parts.Length > 1 ? parts[0] : "教程";
                string body = parts.Length > 1 ? parts[1] : parts[0];
                bool last = _introStep >= steps.Length - 1;
                InformationManager.ShowInquiry(new InquiryData(
                    "新手指引 " + (_introStep + 1) + "/" + steps.Length + " · " + title, body, true, true,
                    last ? "开始统治" : "下一步", "不再提示",
                    delegate
                    {
                        _introStep++;
                        _timer = 0.3f;
                        if (last) _introPending = false;
                    },
                    delegate { TipState.Disable("intro"); _introPending = false; },
                    "", 0f, null, null, null), true, false);
            }
            catch (Exception ex) { DLog.Force("分步教程失败: " + ex.Message); _introPending = false; }
        }

